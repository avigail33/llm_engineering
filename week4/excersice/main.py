
def sum(num1, num2):
    """
    Calculates the sum of two numbers.

    Args:
        num1 (int or float): The first number.
        num2 (int or float): The second number.

    Returns:
        int or float: The sum of num1 and num2.
    """
    # Return the result of adding the two input numbers
    return num1 + num2
